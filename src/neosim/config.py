# ---------------------------------------------------------------------------
# Runtime configuration
# ---------------------------------------------------------------------------
@dataclass(slots=True)
class SimulationConfig:
    """Configuration for a single simulated shift."""

    patient_id: str = "SIM-0001"
    name: str = "Baby Doe"
    gestational_age_weeks: float = 30.0
    birth_weight_g: float = 1250.0
    postnatal_age_days: float = 14.0
    sex: str = "Female"
    condition: str = "stable_preterm"
    severity: float = 0.35
    shift_hours: float = 8.0
    interval_minutes: float = 5.0  # exported resolution; generator runs at 1 min
    start_time: str | None = None
    seed: int | None = None
    cohort: str = "auto"  # auto | premo | pics
    interventions: list[str] = field(default_factory=list)
    care_events: bool = True
    closed_loop: bool = True
    temperature_setpoint: float = 36.8
    target_spo2: float = 94.0


